// DocTruth runner: turns README claims into Kane CLI flows and reports
// TRUE / LIE per claim, with the raw NDJSON evidence saved per run.
//
// Usage:
//   node tool/run.mjs [--base-url http://localhost:8137] [--claims claims.json]
//                     [--out report.md] [--evidence-dir evidence] [--tag run-001]
//
// Requires: `kane-cli login` done first. Exit code: 0 = all claims TRUE,
// 1 = at least one LIE, 2 = a run errored (auth, Chrome, timeout).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(
  process.argv.slice(2).map((a, i, arr) =>
    a.startsWith('--') ? [a.slice(2), arr[i + 1]?.startsWith('--') ? true : arr[i + 1]] : []
  ).filter(([k]) => k)
);

const baseUrl = (args['base-url'] || 'http://localhost:8137').replace(/\/$/, '');
const claimsPath = join(root, args.claims || 'claims.json');
const outPath = join(root, args.out || 'report.md');
const evidenceDir = join(root, args['evidence-dir'] || 'evidence');
const tag = args.tag || `run-${new Date().toISOString().slice(0, 16).replace(/[-:T]/g, '')}`;
const runDir = join(evidenceDir, tag);
mkdirSync(runDir, { recursive: true });

const claims = JSON.parse(readFileSync(claimsPath, 'utf8'));
const results = [];

for (const claim of claims) {
  const url = `${baseUrl}/${claim.page}`;
  const objective = `Verify this claim about the app at ${url}: ${claim.claim} ` +
    `Answer only by what you observe in the browser. If the claim holds, pass. If it does not hold, fail and say what actually happened.`;
  console.log(`\n[${claim.id}] ${claim.claim}`);
  console.log(`  url: ${url}`);

  const proc = spawnSync(
    'kane-cli',
    ['run', '--agent', '--headless', '--url', url, '--final-validation', 'on',
     '--timeout', '420', objective],
    { encoding: 'utf8', timeout: 480_000, maxBuffer: 64 * 1024 * 1024 }
  );

  const rawPath = join(runDir, `${claim.id}.ndjson`);
  writeFileSync(rawPath, (proc.stdout || '') + '\n--- stderr ---\n' + (proc.stderr || ''));

  // Parse the NDJSON stream: the last run_end event carries the verdict.
  let verdict = 'ERROR';
  let summary = '';
  let sessionDir = '';
  for (const line of (proc.stdout || '').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed.startsWith('{')) continue;
    try {
      const ev = JSON.parse(trimmed);
      const type = ev.type || ev.event || '';
      if (type === 'run_end' || ev.status || ev.result) {
        const s = String(ev.status || ev.result || '').toLowerCase();
        if (s.includes('pass')) verdict = 'TRUE';
        else if (s.includes('fail')) verdict = 'LIE';
        summary = ev.summary || ev.message || summary;
        sessionDir = ev.session_dir || ev.sessionDir || sessionDir;
      }
    } catch { /* non-JSON progress line, ignore */ }
  }
  // Fall back to the process exit code: 0 pass, 1 fail, 2 error, 3 timeout.
  if (verdict === 'ERROR') {
    if (proc.status === 0) verdict = 'TRUE';
    else if (proc.status === 1) verdict = 'LIE';
    else verdict = 'ERROR';
  }
  if (!summary) {
    const lines = (proc.stderr || '').split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('Skill update'));
    summary = lines[lines.length - 1] || `exit ${proc.status}`;
  }
  if (proc.status === 3) { verdict = 'ERROR'; summary = 'run timed out'; }

  console.log(`  -> ${verdict} (exit ${proc.status}) ${summary}`);
  results.push({ ...claim, verdict, summary, sessionDir, raw: `${tag}/${claim.id}.ndjson` });
}

const passed = results.filter(r => r.verdict === 'TRUE').length;
const failed = results.filter(r => r.verdict === 'LIE').length;
const errored = results.filter(r => r.verdict === 'ERROR').length;

const md = [
  '# DocTruth report',
  '',
  `Run: \`${tag}\` — base URL: ${baseUrl}`,
  '',
  `**${passed} TRUE, ${failed} LIE, ${errored} ERROR** out of ${results.length} claims.`,
  '',
  '| Claim | Verdict | What Kane found |',
  '|---|---|---|',
  ...results.map(r => `| ${r.id}: ${r.claim} | **${r.verdict}** | ${r.summary.replace(/\|/g, '\\|')} |`),
  '',
  '## Evidence',
  '',
  ...results.map(r => `- ${r.id} (${r.verdict}): raw NDJSON \`${r.raw}\`${r.sessionDir ? `, Kane session \`${r.sessionDir}\`` : ''}`),
  '',
  '_Generated by `tool/run.mjs`. A LIE means the README claim does not hold in the live app — fix the app or the doc, then re-run._',
  '',
].join('\n');
writeFileSync(outPath, md);
console.log(`\nReport written to ${outPath}: ${passed} TRUE, ${failed} LIE, ${errored} ERROR`);

process.exit(errored > 0 ? 2 : failed > 0 ? 1 : 0);
